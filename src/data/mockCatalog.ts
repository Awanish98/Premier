// Helper for Endless Scrolling / Filtered Catalog
export function queryCatalog({
  type = 'all',
  genre = 'All',
  language = 'All',
  searchQuery = '',
  sortBy = 'trending',
  page = 1,
  pageSize = 12,
}: {
  type?: 'all' | 'movie' | 'tv' | 'anime';
  genre?: string;
  language?: string;
  searchQuery?: string;
  sortBy?: SortOption;
  page?: number;
  pageSize?: number;
}): { items: MediaItem[]; hasMore: boolean; total: number } {
  let list = MASTER_MEDIA_ITEMS;

  // Filter Type
  if (type !== 'all') {
    list = list.filter((item) => item.type === type);
  }

  // Filter Genre
  if (genre && genre !== 'All') {
    if (genre === 'Dual Audio' || genre === 'Hindi Dubbed') {
      list = list.filter((item) => item.isDualAudio || item.hasHindiDubbed || item.language === 'Hindi');
    } else {
      list = list.filter((item) => item.genres.some((g) => g.toLowerCase() === genre.toLowerCase()));
    }
  }

  // Filter Language
  if (language && language !== 'All') {
    if (language.toLowerCase() === 'dual audio' || language.toLowerCase() === 'hindi') {
      list = list.filter((item) => item.isDualAudio || item.hasHindiDubbed || item.language?.toLowerCase() === 'hindi');
    } else {
      list = list.filter((item) => item.language?.toLowerCase() === language.toLowerCase());
    }
  }

  // Filter Search
  if (searchQuery.trim()) {
    const q = searchQuery.toLowerCase();
    list = list.filter(
      (item) =>
        item.title.toLowerCase().includes(q) ||
        item.genres.some((g) => g.toLowerCase().includes(q)) ||
        item.overview.toLowerCase().includes(q) ||
        item.cast?.some((c) => c.toLowerCase().includes(q)) ||
        item.director?.toLowerCase().includes(q) ||
        (q.includes('hindi') && (item.language === 'Hindi' || item.isDualAudio || item.hasHindiDubbed)) ||
        (q.includes('dual') && item.isDualAudio)
    );
  }

  // Sort
  if (sortBy === 'top-rated') {
    list = [...list].sort((a, b) => b.rating - a.rating);
  } else if (sortBy === 'newest') {
    list = [...list].sort((a, b) => b.releaseYear - a.releaseYear);
  } else if (sortBy === 'title-asc') {
    list = [...list].sort((a, b) => a.title.localeCompare(b.title));
  } else {
    // Trending default: featured & highest rating
    list = [...list].sort((a, b) => (b.featured ? 1 : 0) - (a.featured ? 1 : 0) || b.rating - a.rating);
  }

  const totalVirtualCount = Math.max(list.length, 60);
  const startIndex = (page - 1) * pageSize;
  const endIndex = startIndex + pageSize;

  if (startIndex >= totalVirtualCount) {
    return { items: [], hasMore: false, total: totalVirtualCount };
  }

  // Build current slice
  const result: MediaItem[] = [];
  for (let i = startIndex; i < endIndex && i < totalVirtualCount; i++) {
    const baseItem = list[i % list.length];
    if (baseItem) {
      if (i < list.length) {
        result.push(baseItem);
      } else {
        result.push({
          ...baseItem,
          id: `${baseItem.id}-p${page}-i${i}`,
          title: `${baseItem.title}`,
        });
      }
    }
  }

  return {
    items: result,
    hasMore: endIndex < totalVirtualCount,
    total: totalVirtualCount,
  };
}
